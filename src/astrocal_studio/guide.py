"""Встроенное руководство.

Текст живёт в коде, а не в отдельном файле рядом с программой, по одной
причине: собранное приложение — это один каталог, и документация должна
открываться из меню «Справка» даже там, где никакого `docs/` нет и интернета
тоже нет. Файл `docs/guide.md` в репозитории генерируется отсюда же, чтобы два
текста не разошлись.
"""
from __future__ import annotations

from pathlib import Path

GUIDE = """
# AstroCalendar Studio — как работать

Программа делает две разные вещи, и их полезно не путать.

**Месячный выпуск** отвечает на вопрос «что произойдёт». Он считается один раз
на месяц вперёд, воспроизводим и проверяем: те же данные — тот же результат.

**Живая лента (LIVE)** отвечает на вопрос «что только что открыли или
уточнили». Она ничего не пересчитывает наперёд, а сравнивает текущее состояние
внешних источников с прошлым снимком.

---

## 1. Первый запуск

При первом запуске данных ещё нет, и программа сама предложит их скачать.
Если окно закрыли — вкладка **Данные** → кнопка **«Скачать недостающее»**
(то же есть в меню *Файл → Скачать недостающие данные*).

| Что качается | Размер | Зачем |
|---|---|---|
| обязательное | ≈138 МБ | эфемериды DE440s, галилеевы спутники, Hipparcos, OpenNGC, линии созвездий, элементы комет |
| необязательное | ≈56 МБ | ленты предсказаний покрытий IOTA и ядра ориентации Луны |

Без обязательных файлов расчёт не запускается — кнопка «Рассчитать» предложит
сначала их скачать. Без необязательных программа работает, но покрытия звёзд
астероидами, либрации и Lunar X останутся пустыми.

Файлы кладутся в каталог `data` рядом с программой. Переменная окружения
`ASTROCAL_HOME` позволяет держать их в другом месте.

---

## 2. Месячный выпуск за пять шагов

1. Слева выберите **год и месяц**, город наблюдения и категории событий.
2. Нажмите **«Рассчитать выпуск»** (Ctrl+R). Расчёт идёт в фоне: окно не
   зависает, снизу видно, какой модуль считается сейчас.
3. В таблице снимите галочки с того, что в пост не пойдёт. Ранги:
   `must` — событие месяца, `interesting` — заметное явление,
   `optional` — верно, но узко, `technical` — служебное.
4. В панели события внизу можно **переписать формулировку**. Расчётный текст
   при этом сохраняется отдельно и всегда доступен кнопкой «Вернуть
   расчётный»: программа никогда не теряет то, что посчитала.
5. Справа во вкладке **Публикация** — готовый текст для Telegram со счётчиком
   символов и разбиением на части по 4096 знаков. Разрыв никогда не проходит
   посреди события.

Порядок строк меняется стрелками; «Добавить событие вручную» (Ctrl+N)
вставляет строку, которой в расчёте нет, — она помечается как ручная и не
выдаётся за результат вычисления.

---

## 3. Проверка перед публикацией

Вкладка **Проверка** показывает итог автоматических проверок:

* формат строки, часовой пояс, попадание в месяц;
* физическая правдоподобность: расстояние до Луны, фаза, блеск планет,
  созвездие, угловые расстояния;
* перевод расстояний NEO в лунные расстояния и разумность скорости;
* сверка положений тел с JPL Horizons.

Флаг **REVIEW** означает, что событие нельзя публиковать не глядя; **WARN** —
что стоит посмотреть. Полный QA-отчёт открывается кнопкой и сохраняется вместе
с выпуском (*Файл → Сохранить выходные файлы*, Ctrl+Shift+S).

---

## 4. Вкладка LIVE

Кнопка **«Обновить сейчас»** делает ровно один цикл обращений к источникам.
Переход по карточкам и переключение фильтров сеть больше не трогают — иначе
внешние сервисы начали бы отвечать отказом по частоте.

Четыре источника:

| Источник | Что даёт | Тип события |
|---|---|---|
| IOTA + JPL Horizons | покрытия звёзд астероидами, пересчитанные по свежей орбите | прогноз |
| CNEOS | близкие пролёты астероидов | прогноз |
| MPC | вновь появившиеся кометы | открытие |
| TNS | новые и сверхновые | открытие |

Разница между прогнозом и открытием принципиальна. Покрытие 19 сентября
известно заранее и может стоять в календаре, свёрстанном первого числа.
Сверхновая, открытая 12 сентября, туда попасть не могла — и программа не
делает вид, что могла.

**Статусы карточек.** «НОВОЕ» — объекта не было в прошлом снимке источника.
«ОБНОВЛЕНО» — данные изменились с прошлого раза. Повторное обновление не
создаёт дубликатов: состояние ленты хранится в `data/live` и переживает
перезапуск.

**Кнопки карточки:** «Подробнее» разворачивает полные данные и отмечает запись
прочитанной; «Карта» строит полосу покрытия или положение на небе; «В выпуск»
переносит запись в текущий месячный выпуск с пометкой происхождения;
«Пост» открывает готовый короткий текст для канала; «Скрыть» убирает запись из
ленты, не удаляя её.

**Счётчик на ярлыке** — число непросмотренных значимых записей.

**Фильтры** скрывают, но не выбрасывают: «Показать все» возвращает всё,
включая скрытое и слабое.

---

## 5. Покрытия звёзд астероидами: почему это отдельная история

Годовой файл предсказаний IOTA считается один раз и потом не обновляется, а
орбита астероида уточняется каждым новым наблюдением. Для объекта со слабой
астрометрией полоса за полгода уезжает на сотни километров, а момент — на часы.

Поэтому программа берёт из ленты только **список кандидатов**, а полосу строит
сама по актуальной эфемериде JPL. В карточке видны возраст прогноза, возраст
решения орбиты и заявленная неопределённость полосы; если прогноз стар, а
событие близко, запись помечается как требующая пересчёта.

Если при очередном обновлении центральная линия сдвинулась больше чем на 20 км,
в ленте появляется отдельное сообщение с прежней и новой полосой. **Ваш
отредактированный текст при этом не трогается** — обновляются только расчётные
данные, и только по вашей команде.

---

## 6. Ключи доступа

Всё, кроме TNS, работает без регистрации. Для новых и сверхновых нужен бот TNS:
скопируйте `.env.example` в `.env` и впишите

    TNS_API_KEY=
    TNS_BOT_ID=
    TNS_BOT_NAME=

Файл `.env` в репозиторий не попадает. Без ключей вкладка «Данные» честно
покажет «нет ключей», а остальные три источника продолжат работать.

Для отправки поста в канал там же нужны `TELEGRAM_BOT_TOKEN` и
`TELEGRAM_CHAT_ID`.

---

## 7. Сохранение работы

Состояние выпуска (галочки, правки, порядок, ручные события) сохраняется в
`workspace/ГГГГ-ММ.astudio.json` автоматически при закрытии окна и по
Ctrl+S. При следующем расчёте решения возвращаются по устойчивому
идентификатору события. Если исходные данные события изменились после вашей
правки, программа скажет об этом отдельно — но текст не перепишет.

---

## 8. Из командной строки

    python scripts/build_calendar.py            # месячный выпуск
    python scripts/refresh_live.py              # обновить живую ленту
    python scripts/refresh_live.py --neo        # только сближения
    python scripts/refresh_live.py --comets     # только новые кометы
    python scripts/refresh_live.py --transients # только TNS
    python scripts/refresh_live.py --json       # машинный вывод

Состояние ленты у программы и у скрипта общее: объект, объявленный новым в
командной строке, в окне новым уже не будет.
"""


def guide_text() -> str:
    return GUIDE.strip() + "\n"


def write(path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(guide_text(), encoding="utf-8")
    return path


if __name__ == "__main__":
    from astrocal import config as cfg

    print(write(cfg.ROOT / "docs" / "guide.md"))

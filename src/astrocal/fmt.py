def date_time_msk(when: dt.datetime) -> str:
    """'07 сентября, 00:30'"""
    return f"{when.day:02d} {MONTHS_GEN[when.month]}, {when:%H:%M}"


def magnitude(value: float) -> str:
    """'V=-4,7m' — знак обязателен, десятичный разделитель — запятая."""
    return f"V={value:+.1f}m".replace(".", ",")


def phase_fraction(illum: float, waxing: bool) -> str:
    """'Ф=+0,21' / 'Ф=-0,21' — знак кодирует растущую/убывающую Луну."""
    sign = "+" if waxing else "-"
    # 1,00 в календарях не пишут: полная фаза обозначается как 0,99
    value = min(illum, 0.99)
    return f"Ф={sign}{value:.2f}".replace(".", ",")


def angle_deg(deg: float) -> str:
    """Углы: >=1° как '2.3°', меньше — как '0°25'."""
    arcmin = int(round(deg * 60))
    if deg >= 1.0 or arcmin >= 60:
        return f"{deg:.1f}°"
    if arcmin == 0:
        return f"{deg * 3600:.0f}″"
    return f"0°{arcmin}′"


def distance_km(km: float) -> str:
    return f"{km:.0f}"


def number(value: float, digits: int = 1, sign: bool = False) -> str:
    """Число с запятой как десятичным разделителем.

    Отдельная функция нужна потому, что соблазн написать
    `f"... {x:.1f} а.е.".replace(".", ",")` приводит к «а,е,» и «Макс,
    длительность»: замена бьёт по всем точкам строки, а не только по
    десятичной. Форматируем число, а не предложение.
    """
    text = f"{value:+.{digits}f}" if sign else f"{value:.{digits}f}"
    return text.replace(".", ",")

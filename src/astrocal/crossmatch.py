"""Когда проход малого тела рядом с объектом каталога достоин строки.

Правила отбора у астероидов и у комет раньше жили порознь и разошлись:
комета рядом с Мессье публиковалась при блеске до 11,5ᵐ, астероид — до 10,5ᵐ,
а пороги по расстоянию отличались вдвое. Читателю эта разница ничего не
объясняет: для него это одинаковые события «малое тело прошло рядом с
объектом». Поэтому пороги вынесены сюда и применяются к обоим.

Три правила предложил Станислав Короткий, исходя из того, что реально стоит
смотреть в телескоп и что имеет смысл снимать:

* рядом с объектом Мессье интересно даже слабое тело — до +19,0ᵐ в пределах
  1°: сам объект яркий, кадр получится в любом случае, а малое тело на нём
  найдётся при обработке;
* рядом с прочими NGC/IC порог строже — +13,0ᵐ в пределах 1°: этих объектов
  тысячи, и без ограничения по блеску календарь заполнят проходы, которые
  никто не увидит;
* рядом со звездой ярче +7,0ᵐ — +13,0ᵐ в пределах 1°: сначала порог был
  вдвое строже, но Станислав его расширил — на градусе сближение ещё
  укладывается в одно поле зрения искателя.

Старые правила не выброшены, а объединены с новыми по «или». Они шире по
расстоянию там, где объект очень яркий: астероид в 2° от звезды 4-й величины
видно в один бинокль, и такую строку терять не хочется.
"""
from __future__ import annotations

# Новые правила: (предел блеска малого тела, предел расстояния в градусах)
MESSIER = (19.0, 1.0)
NGC_IC = (13.0, 1.0)
STAR = (13.0, 1.0)
STAR_OBJECT_LIMIT = 7.0     # правило для звезды работает только для ярких звёзд


def by_new_rules(body_mag: float, kind: str, object_mag: float,
                 is_messier: bool, sep_deg: float) -> bool:
    """Проходит ли сближение по трём правилам Станислава."""
    if kind == "star":
        limit, radius = STAR
        return (object_mag <= STAR_OBJECT_LIMIT and body_mag <= limit
                and sep_deg <= radius)
    limit, radius = MESSIER if is_messier else NGC_IC
    return body_mag <= limit and sep_deg <= radius


def rule_name(body_mag: float, kind: str, object_mag: float,
              is_messier: bool, sep_deg: float) -> str:
    """Каким правилом событие прошло отбор — для протокола расчёта."""
    if by_new_rules(body_mag, kind, object_mag, is_messier, sep_deg):
        if kind == "star":
            return (f"звезда ярче {STAR_OBJECT_LIMIT:+.1f}ᵐ, тело ярче "
                    f"{STAR[0]:+.1f}ᵐ, расстояние до {STAR[1]:.1f}°")
        if is_messier:
            return (f"объект Мессье, тело ярче {MESSIER[0]:+.1f}ᵐ, "
                    f"расстояние до {MESSIER[1]:.1f}°")
        return (f"объект NGC/IC, тело ярче {NGC_IC[0]:+.1f}ᵐ, "
                f"расстояние до {NGC_IC[1]:.1f}°")
    return "прежнее правило отбора"


# Предел блеска малого тела, выше которого кросс-матч вообще не имеет смысла:
# самое мягкое из правил.
BODY_MAG_LIMIT = max(MESSIER[0], NGC_IC[0], STAR[0])

# Предел расстояния, дальше которого не смотрим ни по одному правилу.
# Прежние правила для очень ярких звёзд доходят до 2,5°.
SEARCH_RADIUS_DEG = 2.5
